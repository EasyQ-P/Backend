class SQLiteTx(Tx):
    def execute(self, sql, args=()):
        sql = re.sub(r'\s+FOR UPDATE(?: SKIP LOCKED)?', '', sql, flags=re.I)
        sql = sql.replace('%s', '?').replace('::tsvector', '').replace('::vector', '').replace('::jsonb', '')
        args = tuple(v.isoformat() if isinstance(v, datetime) else v for v in args)
        return self.connection.execute(sql, args)

    def one(self, sql, args=()):
        if "nextval('ws_events_event_id_seq')" in sql:   # no sequences in SQLite: next free number in the same lock
            return {'event_id': self.execute('SELECT coalesce(max(event_id),0)+1 AS n FROM ws_events').fetchone()['n']}
        row = self.execute(sql, args).fetchone()
        return dict(row) if row else None

    def all(self, sql, args=()):
        return [dict(r) for r in self.execute(sql, args).fetchall()]

    def lock(self, key):
        pass  # Database transaction RLock serializes the whole test connection.

    def notify(self, event_id):
        pass  # Test assertions inspect persisted events instead of PostgreSQL NOTIFY.


class SQLiteDatabase:
    def __init__(self, clock):
        self.lock = threading.RLock()
        self.connection = sqlite3.connect(':memory:', check_same_thread=False, isolation_level=None)
        self.connection.row_factory = sqlite3.Row
        self.connection.create_function('now', 0, lambda: clock().isoformat())
        self.connection.create_function('to_tsvector', 2, lambda config, value: value)
        source = SCHEMA.read_text(encoding='utf-8')
        for match in re.finditer(r'CREATE TABLE (\w+) \((.*?)\n\);', source, re.S):
            name, content = match.groups()
            content = re.sub(r'BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL', 'INTEGER', content)
            content = re.sub(r'VECTOR\(768\)|TSVECTOR|JSONB|UUID|TIMESTAMPTZ|BIGINT\[\]', 'TEXT', content)
            content = content.replace('BYTEA', 'BLOB').replace('::jsonb', '')
            content = content.replace('DEFAULT now()', 'DEFAULT (now())')
            self.connection.execute(f'CREATE TABLE {name} ({content})')
        for match in re.finditer(r'CREATE UNIQUE INDEX (\w+) ON (\w+) \(([^;]+);', source):
            self.connection.execute(match[0])
        self.connection.executescript("""
        CREATE VIEW auth_session_view AS SELECT a.auth_session_id,a.token_hash,a.expires_at,a.revoked_at,
          a.user_id,a.participant_id,u.status AS user_status,u.role AS user_role,
          (u.email_verified_at IS NOT NULL) AS email_verified,p.status AS guest_status,
          p.session_id AS guest_session_id,a.csrf_token_hash,a.created_at AS session_created_at
        FROM auth_sessions a LEFT JOIN users u ON u.user_id=a.user_id
        LEFT JOIN participants p ON p.participant_id=a.participant_id;
        """)

    @contextmanager
    def transaction(self):
        with self.lock:
            self.connection.execute('BEGIN')
            try:
                yield SQLiteTx(self.connection)
                self.connection.execute('COMMIT')
            except BaseException:
                self.connection.execute('ROLLBACK')
                raise


class Client:
    def __init__(self, app, origin='https://easyq.test'):
        self.app, self.origin, self.cookies, self.csrf = app, origin, {}, None

    def call(self, method, path, body=None, headers=None, raw=None, upload=None):
        h = {'origin': self.origin}
        if self.csrf:
            h['x-csrf-token'] = self.csrf
        h.update(headers or {})
        if self.cookies:
            h['cookie'] = '; '.join(f'{k}={v}' for k, v in self.cookies.items())
        content = b''
        if upload:
            name, media, data = upload
            h['content-type'] = 'multipart/form-data; boundary=EASYQBOUNDARY'
            content = (f'--EASYQBOUNDARY\r\nContent-Disposition: form-data; name="file"; filename="{name}"\r\nContent-Type: {media}\r\n\r\n').encode() + data + b'\r\n--EASYQBOUNDARY--\r\n'
        elif body is not None:
            h['content-type'] = 'application/json'
            content = dumps(body).encode()
        if raw is not None:
            content = raw
        events = []

        async def run():
            async def receive():
                return {'type': 'http.request', 'body': content}

            async def send(event):
                events.append(event)
            route, _, query = path.partition('?')
            await self.app({'type': 'http', 'method': method, 'path': route, 'query_string': query.encode(),
                'headers': [(k.encode(), v.encode()) for k, v in h.items()], 'client': ('127.0.0.1', 1234)}, receive, send)
        # This sandbox blocks local socketpair(), which Windows asyncio creates
        # even without network I/O. Drive this fully synchronous ASGI exchange
        # directly; replace only the thread executor, never application behavior.
        async def inline(func, *args, **kwargs):
            return func(*args, **kwargs)
        with patch('asyncio.to_thread', inline):
            coroutine = run()
            try:
                coroutine.send(None)
                raise AssertionError('Unexpected asynchronous suspension')
            except StopIteration:
                pass
        status = events[0]['status']
        rh, set_cookies = {}, []
        for k, v in events[0]['headers']:
            if k.decode() == 'set-cookie':
                set_cookies.append(v.decode())
            rh[k.decode()] = v.decode()
        if set_cookies:
            rh['set-cookie'] = ', '.join(set_cookies)
        for value in set_cookies:
            cookie = SimpleCookie()
            cookie.load(value)
            self.cookies.update({k: v.value for k, v in cookie.items()})
        payload = json.loads(events[1]['body']) if events[1]['body'] else None
        if payload and 'data' in payload and isinstance(payload['data'], dict) and 'csrf_token' in payload['data']:
            self.csrf = payload['data']['csrf_token']
        return status, payload, rh


def pptx(pages=('해시 테이블 hash collision 데이터 구조', '벡터 검색과 키워드 검색')):
    out = BytesIO()
    ns = 'http://schemas.openxmlformats.org/presentationml/2006/main'
    relns = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships'
    from xml.sax.saxutils import escape
    with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as z:
        z.writestr('[Content_Types].xml', '<Types/>')
        ids = ''.join(f'<p:sldId id="{i+256}" r:id="rId{i}"/>' for i in range(1, len(pages) + 1))
        z.writestr('ppt/presentation.xml', f'<p:presentation xmlns:p="{ns}" xmlns:r="{relns}"><p:sldIdLst>{ids}</p:sldIdLst></p:presentation>')
        z.writestr('ppt/_rels/presentation.xml.rels', '<Relationships>' + ''.join(f'<Relationship Id="rId{i}" Target="slides/slide{i}.xml"/>' for i in range(1, len(pages) + 1)) + '</Relationships>')
        for i, page in enumerate(pages, 1):
            z.writestr(f'ppt/slides/slide{i}.xml', '<sld xmlns:a="urn:test"><a:p><a:r><a:t>' + escape(page) + '</a:t></a:r></a:p></sld>')
    return out.getvalue()


def pdf(value='Hash collision and vector search'):
    stream = f'BT /F1 12 Tf 72 720 Td ({value}) Tj ET'.encode('ascii')
    objects = [b'<< /Type /Catalog /Pages 2 0 R >>', b'<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
        b'<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
        b'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
        b'<< /Length ' + str(len(stream)).encode() + b' >>\nstream\n' + stream + b'\nendstream']
    result = b'%PDF-1.4\n'
    offsets = []
    for i, content in enumerate(objects, 1):
        offsets.append(len(result))
        result += f'{i} 0 obj\n'.encode() + content + b'\nendobj\n'
    xref = len(result)
    result += b'xref\n0 6\n0000000000 65535 f \n'
    for offset in offsets:
        result += f'{offset:010d} 00000 n \n'.encode()
    return result + f'trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n'.encode()
