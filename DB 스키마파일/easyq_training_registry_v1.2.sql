-- Separate department training-server registry from section 8.2.38.
-- The design lists fields and keys, but not every SQL type; TEXT, JSONB and
-- NUMERIC below are implementation choices. Run against the department DB only.
BEGIN;

CREATE TABLE reg_datasets (
    dataset_version VARCHAR(20) PRIMARY KEY,
    parent_version VARCHAR(20),
    status VARCHAR(20) NOT NULL,
    contains_aihub BOOLEAN NOT NULL DEFAULT false,
    statistics JSONB NOT NULL DEFAULT '{}'::jsonb,
    courses_by_split JSONB NOT NULL DEFAULT '{}'::jsonb,
    gold_in_candidates_rate NUMERIC(6,5),
    script_version VARCHAR(100) NOT NULL,
    retrieval_config_version VARCHAR(50) NOT NULL,
    validation_set_version VARCHAR(20) NOT NULL,
    test_set_version VARCHAR(20) NOT NULL,
    eval_slide_version VARCHAR(20) NOT NULL,
    storage_uri TEXT NOT NULL,
    change_note TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (parent_version) REFERENCES reg_datasets(dataset_version),
    CHECK (gold_in_candidates_rate IS NULL OR gold_in_candidates_rate BETWEEN 0 AND 1)
);

CREATE TABLE reg_test_sets (
    test_set_version VARCHAR(20) PRIMARY KEY,
    test_use_count INTEGER NOT NULL DEFAULT 0 CHECK (test_use_count >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE reg_train_configs (
    config_id UUID PRIMARY KEY,
    config JSONB NOT NULL,
    is_default BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_reg_train_configs_default ON reg_train_configs (is_default) WHERE is_default;

CREATE TABLE reg_jobs (
    job_id VARCHAR(30) PRIMARY KEY,
    type VARCHAR(20) NOT NULL,
    request_id UUID UNIQUE,
    status VARCHAR(20) NOT NULL,
    stage VARCHAR(30),
    hold_reason VARCHAR(40),
    progress NUMERIC(4,3),
    config JSONB,
    curve JSONB,
    best_epoch INTEGER,
    checkpoint_uri TEXT,
    export_job_id VARCHAR(30),
    evaluation_id VARCHAR(30),
    model_version VARCHAR(20),
    result JSONB,
    fault_id UUID,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    CHECK (progress IS NULL OR progress BETWEEN 0 AND 1),
    CHECK (best_epoch IS NULL OR best_epoch >= 0)
);

CREATE TABLE reg_evaluations (
    evaluation_id VARCHAR(30) PRIMARY KEY,
    target VARCHAR(100) NOT NULL,
    dataset_version VARCHAR(20) NOT NULL REFERENCES reg_datasets(dataset_version),
    validation_set_version VARCHAR(20) NOT NULL,
    test_set_version VARCHAR(20) NOT NULL,
    retrieval_config_version VARCHAR(50) NOT NULL,
    threshold NUMERIC(8,5),
    metrics JSONB NOT NULL,
    baselines JSONB NOT NULL,
    llm_only JSONB NOT NULL,
    roc_points JSONB,
    test_use_count INTEGER NOT NULL CHECK (test_use_count >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (threshold IS NULL OR threshold BETWEEN 0 AND 1)
);

CREATE TABLE reg_models (
    model_version VARCHAR(20) PRIMARY KEY,
    dataset_version VARCHAR(20) NOT NULL REFERENCES reg_datasets(dataset_version),
    evaluation_id VARCHAR(30) NOT NULL REFERENCES reg_evaluations(evaluation_id),
    artifact_uri TEXT NOT NULL,
    manifest JSONB NOT NULL,
    threshold NUMERIC(8,5) NOT NULL CHECK (threshold BETWEEN 0 AND 1),
    status VARCHAR(16) NOT NULL CHECK (status IN ('REGISTERED', 'DELETED')),
    deployable BOOLEAN NOT NULL,
    compared_with VARCHAR(20),
    served_before BOOLEAN NOT NULL DEFAULT false,
    memo VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (compared_with) REFERENCES reg_models(model_version)
);

CREATE TABLE reg_deployments (
    deployment_seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode VARCHAR(12) NOT NULL CHECK (mode IN ('CUSTOM', 'LLM_ONLY')),
    serving_version VARCHAR(20) REFERENCES reg_models(model_version),
    previous_version VARCHAR(20) REFERENCES reg_models(model_version),
    threshold NUMERIC(8,5),
    llm_only_threshold NUMERIC(5,2) CHECK (llm_only_threshold BETWEEN 0 AND 101),
    llm_model_id VARCHAR(100),
    llm_prompt_version VARCHAR(100),
    operation VARCHAR(12) NOT NULL CHECK (operation IN ('SWITCH', 'ROLLBACK')),
    reason TEXT NOT NULL,
    deployed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((mode = 'CUSTOM' AND serving_version IS NOT NULL) OR mode = 'LLM_ONLY')
);

CREATE TABLE reg_eval_slide_chunks (
    eval_slide_version VARCHAR(20) NOT NULL,
    chunk_key VARCHAR(100) NOT NULL,
    course_id VARCHAR(100) NOT NULL,
    page_no INTEGER NOT NULL CHECK (page_no > 0),
    text TEXT NOT NULL,
    PRIMARY KEY (eval_slide_version, chunk_key)
);

CREATE TABLE reg_merge_requests (
    request_id UUID PRIMARY KEY,
    base_version VARCHAR(20) NOT NULL REFERENCES reg_datasets(dataset_version),
    result_version VARCHAR(20) REFERENCES reg_datasets(dataset_version),
    added INTEGER NOT NULL DEFAULT 0 CHECK (added >= 0),
    excluded_overlap INTEGER NOT NULL DEFAULT 0 CHECK (excluded_overlap >= 0),
    masked INTEGER NOT NULL DEFAULT 0 CHECK (masked >= 0),
    skipped INTEGER NOT NULL DEFAULT 0 CHECK (skipped >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE reg_faults (
    fault_id UUID PRIMARY KEY,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    code VARCHAR(40) NOT NULL,
    module VARCHAR(100) NOT NULL,
    job_id VARCHAR(30) REFERENCES reg_jobs(job_id),
    message TEXT NOT NULL
);

ALTER TABLE reg_jobs ADD FOREIGN KEY (export_job_id) REFERENCES reg_jobs(job_id);
ALTER TABLE reg_jobs ADD FOREIGN KEY (evaluation_id) REFERENCES reg_evaluations(evaluation_id);
ALTER TABLE reg_jobs ADD FOREIGN KEY (model_version) REFERENCES reg_models(model_version);
ALTER TABLE reg_jobs ADD FOREIGN KEY (fault_id) REFERENCES reg_faults(fault_id);

CREATE INDEX ix_reg_jobs_status_created ON reg_jobs (status, created_at);
CREATE INDEX ix_reg_evaluations_dataset ON reg_evaluations (dataset_version, created_at);
COMMIT;
